// Writes apps/datatug-app/src/ag-grid-license.generated.ts from AG_GRID_LICENSE_KEY (environment first, then
// .env.local). Empty/absent key -> empty string -> community-only build. The key is never printed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const name = 'AG_GRID_LICENSE_KEY';

export function keyFromEnvFile(text) {
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?AG_GRID_LICENSE_KEY\s*=\s*(.*)$/);
    if (m) return m[1].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return '';
}

export function resolveKey(env, envFileText) {
  return (env[name] ?? '').trim() || keyFromEnvFile(envFileText ?? '').trim();
}

export function generatedSource(key) {
  return `// GENERATED by tools/stamp-ag-grid-license.mjs - do not edit or commit.\nexport const AG_GRID_LICENSE_KEY = ${JSON.stringify(key)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const envFile = join(root, '.env.local');
  const key = resolveKey(
    process.env,
    existsSync(envFile) ? readFileSync(envFile, 'utf8') : '',
  );
  writeFileSync(
    join(root, 'apps/datatug-app/src/ag-grid-license.generated.ts'),
    generatedSource(key),
  );
  console.log(
    `[stamp-ag-grid-license] ${key ? 'AG Grid Enterprise key configured' : 'no key: community-only build'}`,
  );
}
